function calculateHexagram(yaoResults) {
    // yaoResults: array of 6 numbers (0=老阴, 1=少阳, 2=少阴, 3=老阳), index 0=初爻 to 5=上爻
    var original = [];
    var changed = [];
    var changingLines = [];

    for (var i = 0; i < 6; i++) {
        var yao = yaoResults[i];
        var isYang = (yao === 1 || yao === 3); // 少阳 or 老阳
        original.push(isYang ? 1 : 0);

        var isChanging = (yao === 0 || yao === 3); // 老阴 or 老阳
        if (isChanging) {
            changingLines.push(i);
            changed.push(isYang ? 0 : 1); // 老阳→阴, 老阴→阳
        } else {
            changed.push(isYang ? 1 : 0);
        }
    }

    var origKey = original.join('');
    var changedKey = changed.join('');

    return {
        original: { binary: origKey, data: HEXAGRAMS[origKey] || null },
        changed: { binary: changedKey, data: HEXAGRAMS[changedKey] || null },
        changingLines: changingLines,
        yaoResults: yaoResults
    };
}

function getNajia(palaceName, lineIndex) {
    var gan = NA_JIA_GAN[palaceName][lineIndex];
    var zhi = NA_JIA_ZHI[palaceName][lineIndex];
    var ganIndex = TIAN_GAN.indexOf(gan);
    var zhiIndex = DI_ZHI.indexOf(zhi);
    var wx = DI_ZHI_WX[zhiIndex];
    return { gan: gan, ganIndex: ganIndex, zhi: zhi, zhiIndex: zhiIndex, wuXing: wx };
}

function getLiuQin(lineWX, palaceWX) {
    if (lineWX === palaceWX) return '兄弟';
    if (WX_SHENG[lineWX] === palaceWX) return '父母';
    if (WX_SHENG[palaceWX] === lineWX) return '子孙';
    if (WX_KE[lineWX] === palaceWX) return '妻财';
    if (WX_KE[palaceWX] === lineWX) return '官鬼';
    return '兄弟';
}

function getLiuShen(dayGanIndex) {
    var startMap = [0, 0, 1, 1, 2, 3, 4, 4, 5, 5]; // 甲乙→0, 丙丁→1, 戊→2, 己→3, 庚辛→4, 壬癸→5
    var start = startMap[dayGanIndex];
    var result = [];
    for (var i = 0; i < 6; i++) {
        result.push(LIU_SHEN[(start + i) % 6]);
    }
    return result;
}

function getShiYing(palaceName, hexBinary) {
    var palace = PALACE_HEXAGRAMS[palaceName];
    if (!palace) return { shi: 0, ying: 2 };
    var keys = palace.keys;
    var shiPos = palace.shiPos;
    var pos = keys.indexOf(hexBinary);
    if (pos === -1) pos = 0;
    return { shi: shiPos[pos], ying: (shiPos[pos] + 3) % 6 };
}

function getFuShen(palaceName, currentLines) {
    // currentLines: array of 6 {gan, zhi, wuXing, liuQin}
    var palaceWX = BA_GUA[palaceName].wuXing;
    var qinTypes = {};
    for (var i = 0; i < 6; i++) {
        if (currentLines[i]) qinTypes[currentLines[i].liuQin] = i;
    }

    var missing = [];
    for (var q = 0; q < LIU_QIN_NAMES.length; q++) {
        if (!(LIU_QIN_NAMES[q] in qinTypes)) {
            missing.push(LIU_QIN_NAMES[q]);
        }
    }

    var fuShenList = [];
    for (var m = 0; m < missing.length; m++) {
        var targetQin = missing[m];
        // Find in palace pure hexagram (first hexagram)
        for (var j = 0; j < 6; j++) {
            var najia = getNajia(palaceName, j);
            var qin = getLiuQin(najia.wuXing, palaceWX);
            if (qin === targetQin) {
                fuShenList.push({ lineIndex: j, qinType: targetQin, fuZhi: najia.zhi, fuGan: najia.gan });
                break;
            }
        }
    }
    return fuShenList;
}

function getGuaShen(palaceName, monthZhiIndex) {
    var palaceZhi = NA_JIA_ZHI[palaceName][0]; // 初爻地支 = 宫主支
    var palaceZhiIdx = DI_ZHI.indexOf(palaceZhi);
    var guaShenZhiIdx = (monthZhiIndex - palaceZhiIdx + 12) % 12;
    var guaShenZhi = DI_ZHI[guaShenZhiIdx];

    // Find which line has this branch
    for (var i = 0; i < 6; i++) {
        var najia = getNajia(palaceName, i);
        if (najia.zhiIndex === guaShenZhiIdx) {
            return { zhi: guaShenZhi, zhiIndex: guaShenZhiIdx, lineIndex: i };
        }
    }
    return null;
}

function getKongWang(dayGanIndex) {
    var pairs = [[10,11],[8,9],[6,7],[4,5],[2,3]]; // 甲己→戌亥, 乙庚→申酉, 丙辛→午未, 丁壬→辰巳, 戊癸→寅卯
    return pairs[Math.floor(dayGanIndex / 2)];
}

function getShenSha(dayZhiIndex, monthZhiIndex) {
    // 三合局
    var sanHe = [[2,6,10],[0,4,8],[1,5,9],[3,7,11]]; // 申子辰, 寅午戌, 巳酉丑, 亥卯未
    // 驿马: 申子辰→寅(2), 寅午戌→申(8), 巳酉丑→亥(11), 亥卯未→巳(5)
    var yiMaTargets = [2, 8, 11, 5];
    // 桃花: 申子辰→酉(9), 寅午戌→卯(3), 巳酉丑→午(6), 亥卯未→子(0)
    var taoHuaTargets = [9, 3, 6, 0];
    // 华盖: 申子辰→辰(4), 寅午戌→戌(10), 巳酉丑→丑(1), 亥卯未→未(7)
    var huaGaiTargets = [4, 10, 1, 7];

    var yiMa = '无', taoHua = '无', huaGai = '无';
    for (var g = 0; g < 4; g++) {
        if (sanHe[g].indexOf(dayZhiIndex) !== -1) {
            yiMa = DI_ZHI[yiMaTargets[g]];
            taoHua = DI_ZHI[taoHuaTargets[g]];
            huaGai = DI_ZHI[huaGaiTargets[g]];
            break;
        }
    }
    return { yiMa: yiMa, taoHua: taoHua, huaGai: huaGai };
}

